DROP TABLE IF EXISTS TB_MSG_MESSAGE;
DROP TABLE IF EXISTS TB_MSG_AUDIT_LOG;

CREATE TABLE TB_MSG_MESSAGE (
    MESSAGE_ID        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MESSAGE_CODE      VARCHAR(50)  NOT NULL UNIQUE,
    MESSAGE_NAME      VARCHAR(100) NOT NULL,
    MESSAGE_TYPE      VARCHAR(20)  NOT NULL,
    CHANNEL_CODE      VARCHAR(30)  NOT NULL,
    LOCALE            VARCHAR(10)  NOT NULL,
    MESSAGE_CONTENT   VARCHAR(4000) NOT NULL,
    DISPLAY_START_AT  TIMESTAMP,
    DISPLAY_END_AT    TIMESTAMP,
    USE_YN            CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_BY        VARCHAR(50) NOT NULL,
    CREATED_AT        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_BY        VARCHAR(50) NOT NULL,
    UPDATED_AT        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX IX_MSG_MESSAGE_01 ON TB_MSG_MESSAGE (MESSAGE_TYPE, CHANNEL_CODE, USE_YN);
CREATE INDEX IX_MSG_MESSAGE_02 ON TB_MSG_MESSAGE (DISPLAY_START_AT, DISPLAY_END_AT);

CREATE TABLE TB_MSG_AUDIT_LOG (
    AUDIT_ID          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    GUID              VARCHAR(80) NOT NULL,
    TRACE_ID          VARCHAR(80) NOT NULL,
    USER_ID           VARCHAR(50) NOT NULL,
    ACTION_TYPE       VARCHAR(30) NOT NULL,
    TARGET_ID         VARCHAR(80),
    RESULT_CODE       VARCHAR(20) NOT NULL,
    CREATED_AT        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
